.data

n: .word 4 # номер студента

.text
.globl main

main:
    # Считываем целое число x
    li   a7, 5
    ecall

    # Сохраняем введённое значение в t0
    mv   t0, a0

    # Загружаем адрес переменной n
    la   t1, n

    # Загружаем значение переменной n в t2
    lw   t2, 0(t1)

    # Сравниваем введённое значение с номером студента
    beq  t0, t2, found

    # Если не совпало, результат 0
    li   a0, 0
    j    print

found:
    # Если совпало, результат 1
    li   a0, 1

print:
    # Вывод результата: 0 или 1
    li   a7, 1
    ecall

    # Завершение программы
    li   a7, 10
    ecall